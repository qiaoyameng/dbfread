"""
Build small Visual FoxPro DBF files with :mod:`struct`.

The files are generated byte by byte from the documented on-disk layout
instead of being produced by an external tool, so every byte can be
reasoned about from the tests.

VFP layout used here (Visual FoxPro 9, versions 0x30/0x31/0x32):

* File header, 32 bytes, little endian:
  ``<BBBBLHHHBBLLLBBH`` -- the same layout parsed by
  :class:`dbfread.dbf.DBFHeader`.
* Field descriptor, 32 bytes, little endian:
  ``<11scLBBHBBBB7sB`` -- the same layout parsed by
  :class:`dbfread.dbf.DBFField`. Byte 18 (the second reserved byte) is
  the VFP flags byte. Its lowest bit (0x01) marks a system field.
* The hidden nullable bitmap field is a type ``'0'`` field named
  ``_NullFlags`` with the system flag (0x01) set. Its length is
  ``ceil(number_of_visible_fields / 8)`` and it is always the last
  field descriptor. Bit *n* of the bitmap corresponds to the *n*-th
  visible field; a set bit means NULL for that record.
* Varchar (``'V'``) and Varbinary (``'Q'``) fields occupy
  ``width + 1`` bytes per record: ``width`` bytes of left-justified
  data padded with ``0x00`` followed by a one-byte length of the
  actual data. Length 0 is an empty value, length == width means the
  value fills the whole field.
* Each record starts with a one-byte marker: ``' '`` (0x20) for a normal
  record, ``'*'`` (0x2a) for a deleted record. The file ends with
  ``0x1a``.
"""
import struct

HEADER_FORMAT = '<BBBBLHHHBBLLLBBH'
HEADER_SIZE = struct.calcsize(HEADER_FORMAT)
FIELD_FORMAT = '<11scLBBHBBBB7sB'
FIELD_SIZE = struct.calcsize(FIELD_FORMAT)
TERMINATOR = b'\x1a'

# VFP field descriptor flag (byte 18): system field.
SYSTEM_FIELD_FLAG = 0x01

RECORD_NORMAL = b' '
RECORD_DELETED = b'*'


def field_descriptor(name, field_type, length, decimal_count=0,
                     system=False):
    """Build one 32-byte Visual FoxPro field descriptor."""
    name_bytes = name.encode('ascii')[:11]
    name_bytes = name_bytes.ljust(11, b'\x00')
    flags = SYSTEM_FIELD_FLAG if system else 0
    return struct.pack(
        FIELD_FORMAT,
        name_bytes,
        field_type.encode('ascii'),
        0,                # address (ignored on disk)
        length,
        decimal_count,
        0,                # reserved1
        0,                # workarea id
        0,                # reserved2
        0,                # reserved3
        0,                # set fields flag
        b'\x00' * 7,      # reserved4
        flags,            # VFP flags byte (index_field_flag slot)
    )


def null_flags_descriptor(num_fields):
    """Build the hidden _NullFlags descriptor for num_fields fields."""
    bitmap_len = (num_fields + 7) // 8
    return field_descriptor(
        '_NullFlags', '0', bitmap_len, system=True)


def file_header(dbversion, num_records, num_fields, record_len,
                language_driver=0x03):
    """Build the 32-byte file header.

    Header length is 32 + 32 * num_fields + 1 (terminator).
    """
    header_len = HEADER_SIZE + FIELD_SIZE * num_fields + 1
    return struct.pack(
        HEADER_FORMAT,
        dbversion,
        108,              # year 2008 (stored as year - 1900)
        1,                # month
        1,                # day
        num_records,
        header_len,
        record_len,
        0,                # reserved1
        0,                # incomplete transaction
        0,                # encryption flag
        0,                # free record thread
        0,                # reserved2
        0,                # reserved3
        0,                # mdx flag
        language_driver,  # 0x03 -> cp1252 (Windows ANSI)
        0,                # reserved4
    )


def build_dbf(path, dbversion, field_specs, records,
              language_driver=0x03, null_flags=True):
    """Write a complete VFP DBF file.

    field_specs is a list of ``(name, type, width)`` tuples.
    records is a list of ``(marker, field_bytes, null_bitmap)`` tuples,
    where field_bytes are the already-encoded bytes of the visible
    fields in descriptor order and null_bitmap is the bytes of the
    ``_NullFlags`` field (or None when the table has no nullable
    bitmap).
    """
    descriptors = b''.join(
        field_descriptor(name, field_type, width)
        for name, field_type, width in field_specs)

    visible_record_len = sum(
        width + (1 if field_type in ('V', 'Q') else 0)
        for _, field_type, width in field_specs)
    bitmap_len = (len(field_specs) + 7) // 8 if null_flags else 0
    record_len = 1 + visible_record_len + bitmap_len

    num_fields = len(field_specs) + (1 if null_flags else 0)
    if null_flags:
        descriptors += null_flags_descriptor(len(field_specs))

    header = file_header(dbversion, len(records), num_fields, record_len,
                         language_driver)

    body = b''
    for marker, field_bytes, bitmap in records:
        if null_flags:
            assert bitmap is not None and len(bitmap) == bitmap_len
        body += marker + field_bytes + (bitmap or b'')

    with open(path, 'wb') as out:
        out.write(header)
        out.write(descriptors)
        out.write(b'\r')
        out.write(body)
        out.write(TERMINATOR)


def varchar_bytes(value, width, encoding='cp1252'):
    """Encode a Varchar value the way VFP stores it inside a record."""
    encoded = value.encode(encoding)
    assert len(encoded) <= width
    return encoded.ljust(width, b'\x00') + bytes([len(encoded)])


def varbinary_bytes(value, width):
    """Encode a Varbinary value the way VFP stores it inside a record."""
    assert len(value) <= width
    return value.ljust(width, b'\x00') + bytes([len(value)])


def fixed_bytes(value, width):
    """Pad a fixed-width character field with spaces."""
    if isinstance(value, str):
        value = value.encode('cp1252')
    return value.ljust(width, b' ')
